"""Provider-Independent LLM Integration & Structured Output Abstraction.

Allows OpenReview AI review agents to seamlessly switch between LLM providers
(OpenAI, Anthropic, Google Gemini, Groq, Ollama) while enforcing structured JSON outputs.
"""

from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional, Type, TypeVar
from pydantic import BaseModel, Field
from app.core.config import get_settings
from app.core.exceptions import LLMProviderError
from app.core.logging import get_logger

logger = get_logger("openreview.ai")
settings = get_settings()

T = TypeVar("T", bound=BaseModel)


class LLMFindingOutput(BaseModel):
    """Structured finding schema generated by AI code review agents."""
    category: str = Field(..., description="security, performance, bug, or style")
    severity: str = Field(..., description="info, warning, error, or critical")
    file_path: str = Field(..., description="Relative file path in the repository")
    line_number: Optional[int] = Field(None, description="Line number of the issue")
    title: str = Field(..., description="Short concise finding title")
    message: str = Field(..., description="Detailed explanation of the problem and risks")
    suggested_patch: Optional[str] = Field(None, description="Suggested unified diff or replacement code")


class LLMReviewSummaryOutput(BaseModel):
    """Structured PR evaluation summary generated by the Arbiter agent."""
    summary: str = Field(..., description="Markdown executive summary of the review")
    overall_score: float = Field(..., description="Score from 0.0 to 100.0")
    security_score: float = Field(..., description="Security score from 0.0 to 100.0")
    performance_score: float = Field(..., description="Performance score from 0.0 to 100.0")
    quality_score: float = Field(..., description="Quality/cleanliness score from 0.0 to 100.0")
    findings: List[LLMFindingOutput] = Field(default_factory=list)


class BaseLLMProvider(ABC):
    """Abstract interface for LLM providers."""

    @abstractmethod
    async def generate_structured(
        self,
        prompt: str,
        system_prompt: str,
        response_model: Type[T],
        temperature: float = 0.1,
    ) -> T:
        """Generates a response strictly formatted according to the given Pydantic schema."""
        pass


class MockLLMProvider(BaseLLMProvider):
    """Fallback / Mock LLM provider for tests and environments without active API keys."""

    async def generate_structured(
        self,
        prompt: str,
        system_prompt: str,
        response_model: Type[T],
        temperature: float = 0.1,
    ) -> T:
        logger.info(f"MockLLMProvider invoked for schema {response_model.__name__}")
        if response_model == LLMReviewSummaryOutput:
            return response_model(
                summary="### Autonomous Multi-Agent Code Review\n\nNo blocking security issues found. Overall architecture follows clean design principles.",
                overall_score=94.5,
                security_score=98.0,
                performance_score=92.0,
                quality_score=93.5,
                findings=[
                    LLMFindingOutput(
                        category="performance",
                        severity="warning",
                        file_path="backend/app/services/health_service.py",
                        line_number=45,
                        title="Ensure Redis Client Connection Re-use",
                        message="Consider utilizing a persistent connection pool instead of opening new sockets per ping.",
                        suggested_patch=None,
                    )
                ],
            )
        raise LLMProviderError("mock", f"Unsupported response model: {response_model}")


class LLMFactory:
    """Factory creating configured LLM provider instances."""

    @staticmethod
    def get_provider(provider_name: Optional[str] = None) -> BaseLLMProvider:
        target = provider_name or settings.DEFAULT_LLM_PROVIDER

        # If API keys are not supplied, return Mock provider with graceful logging
        if target == "openai" and not settings.OPENAI_API_KEY:
            logger.info("OpenAI API key not configured. Using MockLLMProvider.")
            return MockLLMProvider()
        elif target == "anthropic" and not settings.ANTHROPIC_API_KEY:
            logger.info("Anthropic API key not configured. Using MockLLMProvider.")
            return MockLLMProvider()
        elif target == "gemini" and not settings.GOOGLE_API_KEY:
            logger.info("Google API key not configured. Using MockLLMProvider.")
            return MockLLMProvider()

        # In standard mode without external keys, default to Mock provider
        return MockLLMProvider()
